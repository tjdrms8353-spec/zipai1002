CREATE TABLE IF NOT EXISTS community_post_likes (
  post_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  created_at TIMESTAMP NOT NULL,
  PRIMARY KEY (post_id, user_id),
  CONSTRAINT fk_local_likes_post FOREIGN KEY (post_id) REFERENCES community_posts(id) ON DELETE CASCADE,
  CONSTRAINT fk_local_likes_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS oauth_identities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  provider VARCHAR(20) NOT NULL,
  provider_subject VARCHAR(191) NOT NULL,
  provider_email VARCHAR(254) DEFAULT '' NOT NULL,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL,
  CONSTRAINT uk_oauth_provider_subject UNIQUE (provider, provider_subject),
  CONSTRAINT fk_local_oauth_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
